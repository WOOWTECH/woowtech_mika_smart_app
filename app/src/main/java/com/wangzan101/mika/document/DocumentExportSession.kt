package com.wangzan101.mika.document

import android.content.Context
import android.net.Uri
import androidx.compose.runtime.getValue
import androidx.compose.runtime.mutableStateOf
import androidx.compose.runtime.setValue
import com.wangzan101.mika.R
import com.wangzan101.mika.core.document.DocumentException
import com.wangzan101.mika.core.document.DocumentFormat
import com.wangzan101.mika.core.document.DocumentMarkdown
import com.wangzan101.mika.core.document.DocumentModel
import com.wangzan101.mika.core.document.DocumentProblem
import com.wangzan101.mika.core.document.DocumentSection
import kotlinx.coroutines.CancellationException
import kotlinx.coroutines.CoroutineScope
import kotlinx.coroutines.CoroutineDispatcher
import kotlinx.coroutines.Dispatchers
import kotlinx.coroutines.launch
import kotlinx.coroutines.withContext

/** Owned by the process chat state, so rotation and system pickers retain the exact export snapshot. */
internal class DocumentExportSession(
    private val scope: CoroutineScope,
    source: String,
    title: String,
    val language: String,
    format: DocumentFormat,
    private val parseDispatcher: CoroutineDispatcher = Dispatchers.Default,
) {
    var source by mutableStateOf(source); private set
    var title by mutableStateOf(title); private set
    var format by mutableStateOf(format); private set
    var generated by mutableStateOf<GeneratedDocument?>(null); private set
    var tables by mutableStateOf<List<DocumentSection.Table>>(emptyList()); private set
    var tableIndex by mutableStateOf<Int?>(null); private set
    var busy by mutableStateOf(false); private set
    var pendingSave by mutableStateOf<GeneratedDocument?>(null); private set
    var status by mutableStateOf(R.string.document_local_note); private set

    private var validationProblem: DocumentProblem? = null

    fun editSource(value: String) {
        if (!busy) { source = value; validationProblem = null; tableIndex = null; tables = emptyList(); invalidate() }
    }
    fun editTitle(value: String) {
        if (!busy) {
            title = value
            // A title can fix its own validation or the model's combined byte limit.
            if (validationProblem == DocumentProblem.InvalidTitle || validationProblem == DocumentProblem.TooLarge)
                validationProblem = null
            invalidate()
        }
    }
    fun chooseFormat(value: DocumentFormat) { if (!busy) { format = value; invalidate() } }
    fun chooseTable(index: Int) { if (!busy) { tableIndex = index; invalidate() } }
    private fun invalidate() {
        generated = null
        status = validationProblem?.let(::problemText) ?: R.string.document_local_note
    }
    fun failed() { busy = false; pendingSave = null; status = R.string.document_failed }
    fun shareOpened() { status = R.string.document_share_opened }

    fun generate(context: Context) {
        val app = context.applicationContext
        generateWith { model, format, index -> DocumentFiles.generate(app, model, format, index) }
    }

    internal fun generateWith(write: suspend (DocumentModel, DocumentFormat, Int?) -> GeneratedDocument) {
        if (busy) return
        busy = true
        status = R.string.document_generating
        scope.launch {
            try {
                val model = try {
                    withContext(parseDispatcher) { DocumentMarkdown.parse(title, language, source) }
                } catch (e: DocumentException) {
                    validationProblem = e.problem
                    throw e
                }
                validationProblem = null
                tables = model.sections.filterIsInstance<DocumentSection.Table>()
                if (format == DocumentFormat.CSV && tables.size > 1 && tableIndex == null) {
                    status = R.string.document_choose_table
                } else {
                    generated = write(model, format, tableIndex)
                    status = R.string.document_ready
                }
            } catch (e: CancellationException) { throw e
            } catch (e: DocumentException) { status = problemText(e.problem)
            } catch (_: Exception) { status = R.string.document_failed
            } finally { busy = false }
        }
    }

    fun beginSave(): GeneratedDocument? {
        if (busy) return null
        return generated?.also {
            DocumentFiles.retain(it)
            pendingSave = it
            busy = true
            status = R.string.document_save_picker
        }
    }

    fun saveResult(context: Context, uri: Uri?) {
        val document = pendingSave ?: return
        pendingSave = null
        if (uri == null) { busy = false; status = R.string.document_save_cancelled; return }
        status = R.string.document_saving
        val app = context.applicationContext
        scope.launch {
            try {
                DocumentFiles.save(app, document, uri)
                status = R.string.document_saved
            } catch (e: CancellationException) { throw e
            } catch (_: Exception) { status = R.string.document_save_failed
            } finally { busy = false }
        }
    }

    private fun problemText(problem: DocumentProblem): Int = when (problem) {
        DocumentProblem.Empty -> R.string.document_empty
        DocumentProblem.TooLarge -> R.string.document_too_large
        DocumentProblem.RaggedTable -> R.string.document_ragged
        DocumentProblem.EmptyTable -> R.string.document_empty_table
        DocumentProblem.MissingTable -> R.string.document_missing_table
        DocumentProblem.SelectTable -> R.string.document_choose_table
        DocumentProblem.CacheFull -> R.string.document_cache_full
        DocumentProblem.InvalidSchema -> R.string.document_failed
        DocumentProblem.InvalidTitle -> R.string.document_invalid_title
        DocumentProblem.InvalidLanguage -> R.string.document_invalid_language
        DocumentProblem.InvalidContent -> R.string.document_invalid_content
    }
}
