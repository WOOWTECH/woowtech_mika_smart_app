#!/usr/bin/env python3
"""Validate and generate the closed App text API and native localization tables.

Run without --write to check resource/key/parameter/plural parity. Translators
edit Localization/AppText.json; no executable Swift or printf types are accepted.
"""
import argparse
import json
from pathlib import Path
import plistlib
import re

ROOT = Path(__file__).resolve().parents[1]
# As in the Play build (ui.languages=en,zh-Hant). Simplified Chinese was removed
# on 2026-11-13; a Simplified Chinese system shows the zh-Hant tables.
LANGUAGES = ('zh-Hant', 'en')


def validate(catalog):
    if catalog.get('schema_version') != 1 or catalog.get('fallback') != 'zh-Hant' or catalog.get('languages') != list(LANGUAGES):
        raise ValueError('language/fallback contract')
    keys, cases = set(), set()
    for entry in catalog['entries']:
        key, case = entry['key'], entry['case']
        if not re.fullmatch(r'[a-z][a-zA-Z0-9.]*', key) or not re.fullmatch(r'[a-z][a-zA-Z0-9]*', case) or key in keys or case in cases:
            raise ValueError('duplicate/invalid key or case')
        keys.add(key); cases.add(case)
        parameters = entry['parameters']
        if len({p['name'] for p in parameters}) != len(parameters) or any(not re.fullmatch(r'[a-z][a-zA-Z0-9]*', p['name']) or p['type'] not in ('String', 'Int') for p in parameters):
            raise ValueError('parameter contract')
        if set(entry['translations']) != set(LANGUAGES):
            raise ValueError('translation parity')
        plural = entry.get('plural')
        if plural and parameters != [{'name': plural, 'type': 'Int'}]:
            raise ValueError('plural must have one integer count')
        for language, text in entry['translations'].items():
            if plural:
                required = {'one', 'other'} if language == 'en' else {'other'}
                if not isinstance(text, dict) or set(text) != required:
                    raise ValueError('plural categories')
                for form in text.values():
                    if not isinstance(form, str) or not form.strip() or form.count('%lld') != 1 or '%' in form.replace('%lld', '').replace('%%', ''):
                        raise ValueError('plural argument contract')
            else:
                if not isinstance(text, str) or not text.strip():
                    raise ValueError('empty translation')
                remaining = text.replace('%%', '')
                for index, parameter in enumerate(parameters, 1):
                    specifier = f'%{index}$' + ('@' if parameter['type'] == 'String' else 'lld')
                    if remaining.count(specifier) != 1:
                        raise ValueError('parameter count/type mismatch')
                    remaining = remaining.replace(specifier, '')
                if '%' in remaining:
                    raise ValueError('unknown format specifier')
    return catalog


def quote(value):
    # JSON escaping is also valid for these Swift/string-table values.
    return json.dumps(value, ensure_ascii=False)


def outputs(catalog):
    validate(catalog)
    entries = catalog['entries']
    swift = ['// Generated by scripts/generate_app_text.py. Edit Localization/AppText.json.',
             'import Foundation', '', '/// Closed display messages; content from users/models is never a lookup key.',
             'enum AppText: Equatable {']
    for e in entries:
        args = ', '.join(p['name'] + ': ' + p['type'] for p in e['parameters'])
        swift.append('    case ' + e['case'] + ('(' + args + ')' if args else ''))
    swift += ['', '    var key: String {', '        switch self {']
    swift += ['        case .' + e['case'] + ': return ' + quote(e['key']) for e in entries]
    swift += ['        }', '    }', '', '    var arguments: [CVarArg] {', '        switch self {']
    for e in entries:
        ps = e['parameters']
        if ps:
            bindings = ', '.join('let ' + p['name'] for p in ps)
            args = ', '.join(p['name'] if p['type'] == 'String' else 'Int64(' + p['name'] + ')' for p in ps)
            swift.append('        case .' + e['case'] + '(' + bindings + '): return [' + args + ']')
    swift += ['        default: return []', '        }', '    }', '',
              '    /// Emergency fallback also works if packaging omits a table.',
              '    var traditionalFallback: String {', '        switch self {']
    for e in entries:
        text = e['translations']['zh-Hant']
        if isinstance(text, dict): text = text['other']
        swift.append('        case .' + e['case'] + ': return ' + quote(text))
    swift += ['        }', '    }', '}', '']
    result = {'Sources/App/AppText.swift': '\n'.join(swift).encode()}
    for lang in LANGUAGES:
        strings = ['/* Generated from Localization/AppText.json; semantic keys only. */']
        plurals = {}
        for e in entries:
            value = e['translations'][lang]
            if e.get('plural'):
                name = e['plural']
                plurals[e['key']] = {'NSStringLocalizedFormatKey': f'%#@{name}@', name: {
                    'NSStringFormatSpecTypeKey':'NSStringPluralRuleType', 'NSStringFormatValueTypeKey':'lld', **value}}
            else:
                strings.append(quote(e['key']) + ' = ' + quote(value) + ';')
        prefix = f'Sources/App/Resources/{lang}.lproj/App'
        result[prefix + '.strings'] = ('\n'.join(strings) + '\n').encode()
        result[prefix + '.stringsdict'] = plistlib.dumps(plurals, sort_keys=True)
    return result


def stale_tables(root=ROOT):
    """App tables left in a language folder the catalog no longer lists."""
    return sorted(str(path.relative_to(root)) for path in (root / 'Sources/App/Resources').glob('*.lproj/App.*')
                  if path.parent.stem not in LANGUAGES)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--write', action='store_true')
    args = parser.parse_args()
    catalog = json.loads((ROOT / 'Localization/AppText.json').read_text())
    for relative, data in outputs(catalog).items():
        path = ROOT / relative
        if args.write:
            path.parent.mkdir(parents=True, exist_ok=True); path.write_bytes(data)
        elif not path.exists() or path.read_bytes() != data:
            raise SystemExit('resource/API parity failed: ' + relative)
    stale = stale_tables()
    if stale:
        raise SystemExit('resource/API parity failed: stale ' + ', '.join(stale))
    print(json.dumps({'keys': len(catalog['entries']), 'languages': len(LANGUAGES), 'resource_parity': True}))

if __name__ == '__main__': main()
